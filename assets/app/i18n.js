  function buildLong(dict) {
    var list = [];
    for (var k in dict) {
      if (Object.prototype.hasOwnProperty.call(dict, k) && k.length >= 18 && k.indexOf(" ") >= 0) {
        list.push([k, dict[k]]);
      }
    }
    return list.sort(function (a, b) { return b[0].length - a[0].length; });
  }

  var SUBS_EN = SUBS.concat(buildLong(EN)).sort(function (a, b) { return b[0].length - a[0].length; });
  var SUBS_ZH = ZH_SUBS.concat(buildLong(ZH)).sort(function (a, b) { return b[0].length - a[0].length; });

  function tr(s) {
    if (s == null) return s;
    var dict = LANG === "en" ? EN : (LANG === "zh" ? ZH : null);
    if (!dict) return s;
    var rules = LANG === "zh" ? RULES_ZH : RULES;
    var subs = LANG === "zh" ? SUBS_ZH : SUBS_EN;
    var str = String(s);
    if (dict[str] != null) return dict[str];
    var m = str.match(/^(\s*)([\s\S]*?)(\s*)$/);
    var lead = m[1], core = m[2], trail = m[3];
    if (!core) return str;
    if (dict[core] != null) return lead + dict[core] + trail;
    for (var i = 0; i < rules.length; i++) {
      var hit = core.match(rules[i][0]);
      if (hit && rules[i][1]) return lead + rules[i][1].apply(null, hit) + trail;
    }
    var subbed = str;
    for (var j = 0; j < subs.length; j++) {
      if (subbed.indexOf(subs[j][0]) >= 0) {
        subbed = subbed.split(subs[j][0]).join(subs[j][1]);
      }
    }
    if (subbed !== str) {
      subbed = subbed.replace(/(\d+(?:[.,]\d+)?)\s+МБ/g, "$1 MB")
                     .replace(/(\d+(?:[.,]\d+)?)\s+КБ/g, "$1 KB")
                     .replace(/(\d+(?:[.,]\d+)?)\s+ГБ/g, "$1 GB")
                     .replace(/(\d+(?:[.,]\d+)?)\s+Б\b/g, "$1 B");
      return subbed;
    }
    return str;
  }

  var running = false;
  function skip(el) {
    if (!el || !el.closest) return true;
    return !!el.closest("#msgs, #txt, #pin, textarea, input, pre, code, script, style, [data-noi18n]");
  }
  function skipAttr(el) {
    if (!el || !el.closest) return true;
    return !!el.closest("#msgs, #pin, script, style, [data-noi18n]");
  }
  function translateAttrs(root) {
    if (!root.querySelectorAll) return;
    var nodes = root.querySelectorAll("[title], [placeholder], [aria-label]");
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      if (skipAttr(el)) continue;
      ["title", "placeholder", "aria-label"].forEach(function (attr) {
        if (!el.hasAttribute(attr)) return;
        var old = el.getAttribute(attr);
        var v = tr(old);
        if (v !== old) el.setAttribute(attr, v);
      });
    }
  }
  function translateText(root) {
    if (!root) return;
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: function (node) {
        var p = node.parentElement;
        if (!p || skip(p)) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    var node;
    while ((node = walker.nextNode())) {
      var old = node.nodeValue;
      var v = tr(old);
      if (v !== old) node.nodeValue = v;
    }
  }
  function run() {
    if (LANG === "ru" || running) return;
    running = true;
    try {
      translateText(document.body);
      translateAttrs(document.body);
    } finally {
      running = false;
    }
  }

